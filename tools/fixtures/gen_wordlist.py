#!/usr/bin/env python3
"""Generate seed/english.go from monero src/mnemonics/english.h.

Usage:
  python3 -I tools/fixtures/gen_wordlist.py english.h > seed/english.go
"""
import hashlib
import re
import sys

src_path = sys.argv[1]
raw = open(src_path, "rb").read()
src = raw.decode("utf-8")
body = src[src.index("words[NWORDS] ="):]
body = body[:body.index("};")]
words = re.findall(r'"([^"]*)"', body)
if len(words) != 1626:
    sys.exit(f"expected 1626 words, got {len(words)}")
prefix = re.search(r'English\(\): Base\("English", "English", \{\}, (\d+)\)', src).group(1)

out = []
out.append("// Code generated by tools/fixtures/gen_wordlist.py; DO NOT EDIT.\n")
out.append("// Source: monero-project/monero@3fd0f88c20f559839cafb20911cb13cb45eba7bd")
out.append(f"// src/mnemonics/english.h (sha256 {hashlib.sha256(raw).hexdigest()}).\n//")
out.append("// Copyright (c) 2014-2024, The Monero Project")
out.append("// SPDX-License-Identifier: BSD-3-Clause\n")
out.append("package seed\n")
out.append(f"const englishUniquePrefixLength = {prefix}\n")
out.append("var englishWords = [1626]string{")
for i in range(0, len(words), 8):
    out.append("\t" + " ".join(f'"{w}",' for w in words[i:i + 8]))
out.append("}")
sys.stdout.write("\n".join(out) + "\n")
